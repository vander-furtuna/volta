#!/usr/bin/env node
/**
 * Converts the design canvas templates (design/templates/source/*.dc.html) into static HTML pages
 * (design/templates/html/*.html) that open in any browser.
 *
 * The .dc.html files are the visual source of truth. They depend on the canvas runtime
 * (support.js), so this script:
 *   1. moves the <helmet> content into <head>;
 *   2. runs each screen's renderVals() with its initial state;
 *   3. resolves <sc-if> blocks and {{...}} placeholders;
 *   4. strips event handlers and rewrites links between screens.
 * The output is a faithful snapshot of each screen's initial state, with the original CSS.
 *
 * Usage: pnpm templates:export
 */

import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_DIR = path.join(ROOT_DIR, "design/templates/source");
const OUTPUT_DIR = path.join(ROOT_DIR, "design/templates/html");
const SOURCE_EXTENSION = ".dc.html";
const MAX_THUMBNAIL_HEIGHT = 1800;

/** Assets uploaded to the canvas that live as local files in this repository. */
const LOCAL_ASSETS = {
  "/_blob/8f257cea00aa0643b4984beecafd94f3": "../../reference/easymart.png",
};

const SECTIONS = [
  {
    title: "Fluxo principal (desktop)",
    names: ["home", "audience", "offer", "review", "coupon-created", "results"],
  },
  {
    title: "Fluxo principal (mobile)",
    names: [
      "mobile-home",
      "mobile-audience",
      "mobile-offer",
      "mobile-review",
      "mobile-coupon-created",
      "mobile-results",
    ],
  },
  { title: "Fundamentos", names: ["reference", "design-system", "integration", "states"] },
];

function textBetween(text, open, close) {
  const start = text.indexOf(open);
  if (start < 0) return "";
  const end = text.indexOf(close, start + open.length);
  return text.slice(start + open.length, end < 0 ? undefined : end);
}

function escapeHtml(value) {
  return String(value ?? "")
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function decodeAttribute(value) {
  return value.replaceAll("&amp;", "&").replaceAll("&#39;", "'");
}

/** Runs the screen logic with a minimal stand-in for the canvas runtime base class. */
function evaluateRenderValues(script) {
  class DCLogic {
    constructor(props) {
      this.props = props ?? {};
      this.state = {};
    }
    setState() {}
    forceUpdate() {}
  }
  const Component = new Function("DCLogic", `${script}\nreturn Component;`)(DCLogic);
  return new Component({}).renderVals() ?? {};
}

function readPath(values, dottedPath) {
  return dottedPath
    .split(".")
    .reduce((node, key) => (node === null || node === undefined ? undefined : node[key]), values);
}

function renderBody(body, values) {
  let html = body;
  const innermostIf =
    /<sc-if value="\{\{\s*([\w.$]+)\s*\}\}"[^>]*>((?:(?!<sc-if)[\s\S])*?)<\/sc-if>/;
  for (let match = html.match(innermostIf); match; match = html.match(innermostIf)) {
    html = html.replace(match[0], readPath(values, match[1]) ? match[2] : "");
  }
  html = html.replace(/\s+on[A-Z]\w*="\{\{[^}]*\}\}"/g, "");
  html = html.replace(/\{\{\s*([\w.$]+)\s*\}\}/g, (_, dottedPath) =>
    escapeHtml(readPath(values, dottedPath)),
  );
  html = html.replace(/href="([\w-]+)\.dc\.html"/g, 'href="$1.html"');
  for (const [blobUrl, localPath] of Object.entries(LOCAL_ASSETS)) {
    html = html.replaceAll(blobUrl, localPath);
  }
  return html;
}

function parseTemplate(fileName, source) {
  const scriptTag = source.match(
    /<script type="text\/x-dc"[^>]*data-props='([^']*)'[^>]*>([\s\S]*?)<\/script>/,
  );
  const props = scriptTag ? JSON.parse(decodeAttribute(scriptTag[1])) : {};
  return {
    name: fileName.slice(0, -SOURCE_EXTENSION.length),
    title: textBetween(source, "<title>", "</title>").trim(),
    head: textBetween(source, "<helmet>", "</helmet>").trim(),
    body: textBetween(source, "<x-dc>", "</x-dc>").replace(/<helmet>[\s\S]*?<\/helmet>/, ""),
    values: scriptTag ? evaluateRenderValues(scriptTag[2]) : {},
    width: props.$preview?.width ?? 1440,
    height: props.$preview?.height ?? 900,
  };
}

function renderPage(template, sourceFile) {
  return `<!doctype html>
<html lang="pt-BR">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${template.title}</title>
<!-- Generated by scripts/export-templates.mjs from design/templates/source/${sourceFile}. Do not edit by hand. -->
${template.head}
</head>
<body>
${renderBody(template.body, template.values).trim()}
</body>
</html>
`;
}

function renderThumbnail(template) {
  const scale = template.width > 600 ? 0.22 : 0.5;
  const height = Math.min(template.height, MAX_THUMBNAIL_HEIGHT);
  return `<a class="screen" href="${template.name}.html">
  <span class="frame" style="width:${Math.round(template.width * scale)}px;height:${Math.round(height * scale)}px">
    <iframe src="${template.name}.html" title="${escapeHtml(template.title)}" tabindex="-1" loading="lazy" style="width:${template.width}px;height:${height}px;transform:scale(${scale})"></iframe>
  </span>
  <span class="name">${template.name}.html</span>
</a>`;
}

function renderIndex(templates) {
  const byName = new Map(templates.map((t) => [t.name, t]));
  const sections = SECTIONS.map(({ title, names }) => {
    const cards = names.filter((n) => byName.has(n)).map((n) => renderThumbnail(byName.get(n)));
    return `<h2>${title}</h2>\n<div class="grid">\n${cards.join("\n")}\n</div>`;
  });
  return `<!doctype html>
<html lang="pt-BR">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Volta: templates de tela</title>
<!-- Generated by scripts/export-templates.mjs. Do not edit by hand. -->
<style>
body{margin:0;padding:40px;background:#F5F6F1;color:#14231B;font-family:system-ui,sans-serif}
h1{margin:0 0 8px;font-size:28px}
p{margin:0 0 32px;color:#4D5B53;max-width:70ch;line-height:1.5}
h2{margin:40px 0 16px;font-size:18px}
.grid{display:flex;flex-wrap:wrap;gap:24px;align-items:flex-start}
.screen{display:flex;flex-direction:column;gap:8px;text-decoration:none;color:#14231B}
.frame{display:block;overflow:hidden;border-radius:12px;border:1px solid #E3E6DF;background:#fff}
.frame iframe{border:0;transform-origin:0 0;pointer-events:none}
.name{font-size:13px;font-weight:600}
.screen:focus-visible{outline:3px solid #CC4A14;outline-offset:4px}
</style>
</head>
<body>
<h1>Templates de tela do Volta</h1>
<p>Retratos estáticos do estado inicial de cada tela do canvas de design. Abra uma tela para inspecionar o HTML e o CSS exatos. A fonte de verdade é design/templates/source.</p>
${sections.join("\n")}
</body>
</html>
`;
}

async function main() {
  await mkdir(OUTPUT_DIR, { recursive: true });
  const files = (await readdir(SOURCE_DIR)).filter((f) => f.endsWith(SOURCE_EXTENSION)).sort();
  const templates = [];

  for (const file of files) {
    const template = parseTemplate(file, await readFile(path.join(SOURCE_DIR, file), "utf8"));
    await writeFile(path.join(OUTPUT_DIR, `${template.name}.html`), renderPage(template, file));
    templates.push(template);
  }

  await writeFile(path.join(OUTPUT_DIR, "index.html"), renderIndex(templates));
  console.log(`Exported ${templates.length} screens to ${path.relative(ROOT_DIR, OUTPUT_DIR)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
